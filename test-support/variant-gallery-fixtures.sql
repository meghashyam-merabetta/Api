-- Only for disposable gallery test databases.
CREATE TABLE IF NOT EXISTS vendors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, vendor_code VARCHAR(100) NOT NULL UNIQUE,
 name VARCHAR(255) NOT NULL, vendor_status VARCHAR(20) NOT NULL DEFAULT 'pending',
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS vendor_products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vendor_id BIGINT NOT NULL REFERENCES vendors(id), variant_id BIGINT NOT NULL REFERENCES product_variants(id),
 vendor_sku VARCHAR(100), cost_price NUMERIC(12,2), selling_price NUMERIC(12,2) NOT NULL,
 mrp NUMERIC(12,2), currency CHAR(3) NOT NULL DEFAULT 'INR', offer_status VARCHAR(20) NOT NULL DEFAULT 'active',
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(vendor_id,variant_id)
);
CREATE TABLE IF NOT EXISTS inventory (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vendor_product_id BIGINT REFERENCES vendor_products(id), warehouse_code VARCHAR(100) NOT NULL DEFAULT 'DEFAULT',
 quantity_on_hand INTEGER NOT NULL DEFAULT 0 CHECK(quantity_on_hand>=0),
 quantity_reserved INTEGER NOT NULL DEFAULT 0 CHECK(quantity_reserved>=0),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), CHECK(quantity_reserved<=quantity_on_hand), UNIQUE(vendor_product_id,warehouse_code)
);

CREATE TABLE independent_product_images (
 product_id BIGINT NOT NULL REFERENCES products(id),
 source_image_id BIGINT NOT NULL REFERENCES product_images(id),
 sort_order INTEGER NOT NULL DEFAULT 0,
 is_primary BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY(product_id,source_image_id)
);
