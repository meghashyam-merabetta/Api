CREATE OR REPLACE FUNCTION catalog_history_immutable() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Catalog history is append-only' USING ERRCODE='42501'; END $$;
DO $$ DECLARE t TEXT; BEGIN
 FOREACH t IN ARRAY ARRAY['audit_logs','stock_movements'] LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS immutable_history ON %I',t);
  EXECUTE format('CREATE TRIGGER immutable_history BEFORE UPDATE OR DELETE OR TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION catalog_history_immutable()',t);
 END LOOP;
END $$;
CREATE OR REPLACE FUNCTION catalog_metadata() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE actor UUID := NULLIF(current_setting('catalog.actor',true),'')::uuid;
BEGIN
 IF TG_OP='INSERT' THEN NEW.created_by:=actor; ELSE NEW.created_by:=OLD.created_by; NEW.created_at:=OLD.created_at; END IF;
 NEW.updated_by:=actor;
 NEW.updated_at:=clock_timestamp();
 RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION catalog_audit_row() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE before_row JSONB; after_row JSONB; fields TEXT[]; entity TEXT; ident TEXT;
BEGIN
 IF TG_OP<>'INSERT' THEN before_row:=to_jsonb(OLD); END IF;
 IF TG_OP<>'DELETE' THEN after_row:=to_jsonb(NEW); END IF;
 SELECT array_agg(key ORDER BY key) INTO fields FROM (
  SELECT key FROM jsonb_object_keys(COALESCE(before_row,'{}') || COALESCE(after_row,'{}')) key
  WHERE key NOT IN ('created_at','updated_at','created_by','updated_by') AND (before_row->key IS DISTINCT FROM after_row->key)
 ) changed;
 IF fields IS NULL THEN RETURN NULL; END IF;
 entity:=TG_ARGV[0]; ident:=COALESCE(after_row->>'id',before_row->>'id');
 IF entity='product_inventory' THEN ident:=COALESCE(after_row->>'product_id',before_row->>'product_id','unmapped:'||ident); END IF;
 IF entity='product_image' THEN ident:=COALESCE(after_row->>'product_id',before_row->>'product_id'); END IF;
 INSERT INTO audit_logs(entity_type,entity_id,action,old_values,new_values,changed_fields,changed_by,actor_type,request_id,reason)
 VALUES(entity,ident,lower(TG_OP),before_row,after_row,fields,NULLIF(current_setting('catalog.actor',true),'')::uuid,
 COALESCE(NULLIF(current_setting('catalog.actor_type',true),''),'system'),NULLIF(current_setting('catalog.request_id',true),''),NULLIF(current_setting('catalog.reason',true),''));
 RETURN NULL;
END $$;
DO $$ DECLARE t TEXT; kind TEXT; BEGIN
 FOREACH t IN ARRAY ARRAY['products','categories'] LOOP
  kind:=CASE WHEN t='products' THEN 'product' ELSE 'category' END;
  EXECUTE format('DROP TRIGGER IF EXISTS catalog_metadata ON %I',t);
  EXECUTE format('CREATE TRIGGER catalog_metadata BEFORE INSERT OR UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION catalog_metadata()',t);
  EXECUTE format('DROP TRIGGER IF EXISTS catalog_audit ON %I',t);
  EXECUTE format('CREATE TRIGGER catalog_audit AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION catalog_audit_row(%L)',t,kind);
 END LOOP;
END $$;
