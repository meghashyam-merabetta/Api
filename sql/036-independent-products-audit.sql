CREATE OR REPLACE FUNCTION catalog_inventory_movement() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE b INTEGER:=0; r INTEGER:=0; actor UUID:=NULLIF(current_setting('catalog.actor',true),'')::uuid;
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Inventory records must be retained; adjust quantities instead'; END IF;
 IF TG_OP='UPDATE' THEN
  b:=OLD.quantity_on_hand; r:=OLD.quantity_reserved;
  IF OLD.product_id IS NOT NULL AND NEW.product_id IS DISTINCT FROM OLD.product_id THEN RAISE EXCEPTION 'Inventory product ownership is immutable'; END IF;
 END IF;
 NEW.updated_at:=clock_timestamp(); NEW.updated_by:=actor;
 IF TG_OP='INSERT' OR b<>NEW.quantity_on_hand OR r<>NEW.quantity_reserved OR (TG_OP='UPDATE' AND OLD.product_id IS DISTINCT FROM NEW.product_id) THEN
  INSERT INTO stock_movements(product_id,inventory_id,warehouse_code,quantity_before,quantity_changed,quantity_after,
   on_hand_before,on_hand_after,reserved_before,reserved_after,movement_type,changed_by,actor_type,order_id,reason,request_id)
  VALUES(NEW.product_id,NEW.id,NEW.warehouse_code,b,NEW.quantity_on_hand-b,NEW.quantity_on_hand,
   b,NEW.quantity_on_hand,r,NEW.quantity_reserved,COALESCE(NULLIF(current_setting('catalog.movement_type',true),''),'correction'),actor,
   COALESCE(NULLIF(current_setting('catalog.actor_type',true),''),'system'),NULLIF(current_setting('catalog.order_id',true),''),NULLIF(current_setting('catalog.reason',true),''),NULLIF(current_setting('catalog.request_id',true),''));
 END IF;
 RETURN NEW;
END $$;
