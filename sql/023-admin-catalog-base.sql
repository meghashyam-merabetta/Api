CREATE TABLE IF NOT EXISTS brands (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL, slug VARCHAR(180) NOT NULL UNIQUE,
 description TEXT, logo_url TEXT, is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(150) NOT NULL,
 slug VARCHAR(180) NOT NULL UNIQUE, parent_id BIGINT REFERENCES categories(id),
 image_url TEXT, description TEXT, sort_order INTEGER NOT NULL DEFAULT 0,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255) NOT NULL,
 slug VARCHAR(280) NOT NULL UNIQUE, brand_id BIGINT REFERENCES brands(id),
 description TEXT, short_description TEXT, product_status VARCHAR(20) NOT NULL DEFAULT 'draft',
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS product_categories (
 product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
 category_id BIGINT NOT NULL REFERENCES categories(id), is_primary BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY(product_id, category_id)
);
