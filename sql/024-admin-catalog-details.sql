 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE, values JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS product_variants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
 sku VARCHAR(100) NOT NULL UNIQUE, attributes JSONB NOT NULL,
 regular_price NUMERIC(12,2), sale_price NUMERIC(12,2),
 stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK(stock_quantity >= 0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(product_id, attributes),
 CHECK(regular_price IS NULL OR regular_price >= 0),
 CHECK(sale_price IS NULL OR (regular_price IS NOT NULL AND sale_price >= 0 AND sale_price <= regular_price))
);
CREATE INDEX IF NOT EXISTS product_variants_product_id_idx ON product_variants(product_id);
